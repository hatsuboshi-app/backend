import { EC, ERROR_MAPPING, ErrorStatus } from "@/lib/errorCodes"

export default class ControllerError extends Error {
    public name = "ControllerError"
    public code: EC
    public status: ErrorStatus
    public details?: { [key: string]: any }

    constructor(code: EC, message?: string, details?: { [key: string]: any }) {
        super(message ?? code)
        this.code = code
        this.status = ERROR_MAPPING[code]
        this.details = details
    }

    get payload(): ErrorResponse<ErrorStatus, EC> {
        return {
            status: this.status,
            code: this.code,
            message: this.message,
            details: this.details
        }
    }
}

/**
 * Error payload returned by all API endpoints on failure.
 */
export type ErrorResponse<S extends number, E extends EC> = {
    /**
     * HTTP status code generated by the origin server for the failure.
     */
    status: S

    /**
     * Machine-readable code of the specific error that occurred.
     */
    code: E

    /**
     * Human-readable message summarizing the cause of the failure.
     */
    message: string

    /**
     * Additional error details.
     */
    details?: { [key: string]: any }
}
